-- Execute em um banco de exercícios, não no arquivo aberto por outra aplicação.
CREATE TABLE IF NOT EXISTS aluno (
    matricula VARCHAR(30) PRIMARY KEY, -- A chave impede duas linhas com a mesma matrícula.
    nome VARCHAR(120) NOT NULL -- NOT NULL exige que a coluna tenha um valor.
);
INSERT INTO aluno (matricula, nome) VALUES ('001', 'Ana');
SELECT matricula, nome FROM aluno ORDER BY nome;
UPDATE aluno SET nome = 'Ana Maria' WHERE matricula = '001'; -- WHERE limita quais linhas serão alteradas.
DELETE FROM aluno WHERE matricula = '001';

-- Exemplo separado para estudar relacionamento de um aluno com vários endereços.
CREATE TABLE IF NOT EXISTS endereco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_matricula VARCHAR(30) NOT NULL REFERENCES aluno(matricula), -- Chave estrangeira exige aluno existente.
    cidade VARCHAR(120) NOT NULL
);
-- O JOIN combina os registros relacionados das duas tabelas.
SELECT a.nome, e.cidade FROM aluno a JOIN endereco e ON e.aluno_matricula = a.matricula;
